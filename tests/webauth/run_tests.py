"""Host test of the web login (HeishaMon/src/common/webauth.cpp).

1. Builds test_webauth.cpp with the real webauth.cpp and webserver.cpp
   (g++, stubs of tests/webserver), once with the ESP8266 and once with
   the ESP32 buffer size, and runs it: password hash against hashlib
   vectors, sessions, lockout, Host and Origin checks, and requests
   end to end through the webserver, including the bypass attempts.
2. Route table completeness: every route number webserver_cb() in
   HeishaMon.ino (and webfunctions.cpp) uses must be in webauth_routes[]
   (deny by default needs every route to be classified). The check is
   also run on a changed copy, to show that it fails.
3. /getsettings: only "password set" and "API key set" go out, never the
   hash, the salt or the API key.

Run: python3 tests/webauth/run_tests.py
"""

import hashlib
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
OUT = HERE / "build"
OUT.mkdir(parents=True, exist_ok=True)
SKETCH = ROOT / "HeishaMon"
COMMON = SKETCH / "src" / "common"

compiler = shutil.which("g++")
if not compiler:
    raise SystemExit("g++ is required")


def c_string(data: bytes) -> str:
    return '"' + "".join(f"\\x{b:02x}" for b in data) + '"'


# --- vectors from hashlib, not from the code under test ---
sha_inputs = [b"", b"abc", b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq", b"a" * 1000, bytes(range(256)) * 3]
pbkdf2_inputs = [
    (b"password", b"salt", 1),
    (b"password", b"salt", 2),
    (b"password", b"salt", 4096),
    (b"passwordPASSWORDpassword", b"saltSALTsaltSALTsaltSALTsaltSALTsalt", 4096),
    (b"correct horse battery", bytes(range(16)), 2000),
    (b"x" * 64, bytes(range(16, 32)), 10),   # a key of exactly one block
    (b"y" * 65, bytes(range(16, 32)), 10),   # a longer key is hashed first
    (b"", b"\x00" * 16, 3),
]
lines = ["// generated by run_tests.py with hashlib", "#include <string>", "struct sha_vector_t { std::string msg; const char *hex; };",
         "struct pbkdf2_vector_t { std::string password; std::string salt; unsigned iterations; const char *hex; };",
         "static const sha_vector_t sha256_vectors[] = {"]
for m in sha_inputs:
    lines.append(f"  {{ std::string({c_string(m)}, {len(m)}), \"{hashlib.sha256(m).hexdigest()}\" }},")
lines.append("};")
lines.append("static const pbkdf2_vector_t pbkdf2_vectors[] = {")
for p, s, c in pbkdf2_inputs:
    dk = hashlib.pbkdf2_hmac("sha256", p, s, c, 32).hex()
    lines.append(f"  {{ std::string({c_string(p)}, {len(p)}), std::string({c_string(s)}, {len(s)}), {c}, \"{dk}\" }},")
lines.append("};")
(OUT / "vectors.h").write_text("\n".join(lines) + "\n")

sources = [HERE / "test_webauth.cpp"] + [
    COMMON / name for name in ("webauth.cpp", "webserver.cpp", "strnstr.cpp", "strncasestr.cpp", "base64.cpp", "sha1.cpp")
]

executable = None
for size in (128, 512):
    executable = OUT / f"test_webauth_{size}"
    subprocess.run(
        [compiler, "-std=c++17", "-g", "-O1", "-Wall", "-Wno-write-strings", "-Wno-unused-function", "-Wno-register",
         "-fsanitize=address,undefined", "-fno-sanitize-recover=undefined", "-DWEBAUTH_ALL_ROUTES",
         f"-DWEBSERVER_BUFFER_SIZE={size}", "-I" + str(ROOT / "tests" / "webserver" / "stubs"), "-I" + str(COMMON), "-I" + str(OUT)]
        + [str(s) for s in sources] + ["-o", str(executable)],
        check=True,
    )
    subprocess.run([str(executable)], check=True)

# --- route table completeness ---
table = {int(x) for x in subprocess.run([str(executable), "--routes"], check=True, capture_output=True, text=True).stdout.split()}


def used_routes(ino: str, others: list) -> set:
    start = ino.index("int8_t webserver_cb(")
    end = ino.index("\nvoid setupHttp()", start)
    body = ino[start:end]
    found = {int(x) for x in re.findall(r"\bcase\s+(\d+)\s*:", body)}
    found |= {int(x) for x in re.findall(r"->route\s*=\s*(\d+)", body)}
    for text in others:
        found |= {int(x) for x in re.findall(r"->route\s*=\s*(\d+)", text)}
    return found


def missing(ino: str, others: list) -> set:
    return used_routes(ino, others) - table


ino = (SKETCH / "HeishaMon.ino").read_text()
others = [(SKETCH / "webfunctions.cpp").read_text()]
gone = missing(ino, others)
if gone:
    sys.exit(f"FAIL: route numbers used in webserver_cb() without an entry in webauth_routes[] (webauth.cpp): {sorted(gone)}")
used = used_routes(ino, others)
if len(used) < 25:
    sys.exit(f"FAIL: only {len(used)} route numbers found in webserver_cb(), the extraction is broken")
# the check itself must be able to fail: a new route without a table entry
changed = ino.replace("case 20: {", "case 77: {\n            } break;\n          case 20: {", 1)
if missing(changed, others) != {77}:
    sys.exit("FAIL: the route completeness check does not see a new case")
if missing(ino, others + ["client->route = 78;"]) != {78}:
    sys.exit("FAIL: the route completeness check does not see a route set in another file")
# the decision is made by webauth_request() in the REQUEST event
if "webauth_request(client, req, &env)" not in ino:
    sys.exit("FAIL: webserver_cb() does not call webauth_request()")
print(f"PASS: route table has all {len(used)} route numbers of webserver_cb()")

# --- /getsettings never sends the credentials ---
wf = others[0]
start = wf.index("int getSettings(")
end = wf.index("\nint ", start + 10)
body = wf[start:end]
for secret in ("password_hash", "apikey_hash", "salt", "webauth_store.hosts", "iterations"):
    if secret in body:
        sys.exit(f"FAIL: getSettings() uses {secret}")
if "web_password_set" not in body or "web_apikey_set" not in body:
    sys.exit("FAIL: getSettings() does not say whether a password and an API key are set")
if re.search(r"webauth", (SKETCH / "webfunctions.cpp").read_text().split("void settingsToJson(", 1)[1].split("\n}", 1)[0]):
    sys.exit("FAIL: settingsToJson() (config.json, settings export) contains web login data")
# never log a password or a key
for name, text in (("webauth.cpp", (COMMON / "webauth.cpp").read_text()),):
    if "log_message" in text or "printf(" in text.replace("snprintf", ""):
        sys.exit(f"FAIL: {name} logs")
print("PASS: /getsettings and config.json without web login secrets")

# --- firmware glue that cannot run on the host: the calls must be there ---
def need(text, pattern, what):
    if not re.search(pattern, text, re.S):
        sys.exit(f"FAIL: {what}")


setup_ota = ino.split("void setupOTA() {", 1)[1].split("\n}", 1)[0]
need(setup_ota, r"webauth_login_on\(\).*return;.*webauth_ota_allowed\(heishamonSettings\.ota_password\).*return;.*ArduinoOTA\.begin\(\)",
     "setupOTA() must not start ArduinoOTA with the login on or the default password")
need(ino, r"if \(otaRunning\) \{\s*if \(webauth_ota_allowed\(heishamonSettings\.ota_password\)\) \{\s*ArduinoOTA\.handle\(\);",
     "loop() must stop serving ArduinoOTA once the login is on")
if ino.count("ArduinoOTA.handle()") != 1:
    sys.exit("FAIL: ArduinoOTA.handle() outside the guarded place")
need(ino, r"webauth_tick\(\);", "loop() must call webauth_tick()")
need(wf, r"webauth_device_hosts\(out, size, list, n, heishamonSettings->wifi_hostname\)", "device hosts not built by webauth_device_hosts()")
sec = wf.split("int handleSecurity(", 1)[1].split("\nint ", 1)[0]
need(sec, r"sendEscaped\(client, hosts\);.*sendEscaped\(client, webauth_store\.hosts\);", "/security must escape the host names")
if re.search(r"webserver_send_content\(client, (hosts|webauth_store\.hosts)", sec):
    sys.exit("FAIL: /security prints host names without escaping")
# the web login is a tab of the settings (at /security), not a menu entry of its own
html = (ROOT / "HeishaMon" / "htmlcode.h").read_text(encoding="utf-8")
side = html.split("id='sideNav'", 1)[1].split("</nav>", 1)[0]
if "/security" in side or 'href="/settings"' not in side:
    sys.exit("FAIL: the menu must have Settings and no entry of its own for /security")
form1 = html.split("static const char settingsForm1[]", 1)[1].split("<form", 1)[0]
need(form1, r"id='settings_tabs'.*location\.href='/security'\">Web login</button>\s*</nav>", "the settings need a Web login tab that opens /security")
sec_open = html.split("static const char webBodySecurityOpen[]", 1)[1].split(')===="', 1)[0]
need(sec_open, r"id='settings_tabs'.*/settings#basic.*/settings#heatpump.*/settings#io.*/settings#advanced.*/settings#system.*class='active'>Web login</button>",
     "/security must show the tabs of the settings with Web login active")
for tab in re.findall(r"/settings#(\w+)", sec_open):
    if f"data-tab='{tab}' onclick" not in form1:
        sys.exit(f"FAIL: /security links to the settings tab '{tab}' that does not exist")
if len(re.findall(r"data-tab='\w+' onclick", form1)) != len(re.findall(r"/settings#\w+", sec_open)):
    sys.exit("FAIL: /security does not show every tab of the settings")
need(sec, r"sendBodyStart\(client\);\s*webserver_send_content_P\(client, webBodySecurityOpen,", "/security must start with the menu and the tabs of the settings")
need(wf, r"strcmp\(tmp->name\.c_str\(\), \"wifi_hostname\"\) == 0\) \{\s*if \(webauth_hostname_valid\(", "saveSettings() must validate the hostname")
need(wf, r"strlcpy\(heishamonSettings->wifi_hostname, jsonDoc\[F\(\"wifi_hostname\"\)\].*?webauth_hostname_valid\(heishamonSettings->wifi_hostname\)",
     "loadSettings() must validate the stored hostname")
need(wf, r"webauth_load_failed\(\);", "a damaged /webauth.bin must keep the login on")
if re.search(r"strlcpy\(heishamonSettings->wifi_hostname, \"HeishaMon\"", wf):
    sys.exit("FAIL: a stored hostname must be kept (MQTT client id, DHCP, mDNS), only left out of the Host allowlist")
need(wf, r"webauth_hostname_valid\(heishamonSettings->wifi_hostname\) \? heishamonSettings->wifi_hostname : \"heishamon\"",
     "the reconnect page must only print a valid hostname")
need(wf, r"WEBAUTH_LOAD_NEWER\) \{\s*//[^\n]*\n\s*webauth_load_failed\(\);", "a /webauth.bin of a newer firmware must keep the login on")
need(wf, r"WEBAUTH_LOAD_MIGRATED\) \{.*?webauth_save\(\);", "a migrated /webauth.bin must be saved in the current format")
need(wf, r"LittleFS\.rename\(WEBAUTH_FILE_TMP, WEBAUTH_FILE\)", "/webauth.bin must be written through a temporary file")
print("PASS: firmware glue (OTA, hostname, escaping, persistence)")

print("PASS: webauth host tests")
